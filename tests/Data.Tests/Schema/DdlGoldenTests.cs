using CL.Data;
using CL.Data.Configuration;
using CL.Data.Mapping;
using CL.Data.MySql;
using CL.Data.PostgreSql;
using CL.Data.Providers;
using CL.Data.Schema;
using CL.Data.Sqlite;
using CL.Data.SqlServer;
using CodeLogic.Core.Results;

namespace Data.Tests.Schema;

[Table(Name = "ddl_owner")]
public sealed class DdlOwner
{
    [Column(Primary = true, AutoIncrement = true)] public long Id { get; set; }
}

[Table(Name = "ddl_items")]
public sealed class DdlItem
{
    [Column(Primary = true, AutoIncrement = true)] public long Id { get; set; }
    [Column(Size = 40, Unique = true)] public string Code { get; set; } = "";
    public string? Note { get; set; }
    public bool Active { get; set; }
    [ForeignKey<DdlOwner>(nameof(DdlOwner.Id), OnDelete = ForeignKeyAction.Cascade)] public long OwnerId { get; set; }
}

public sealed class DdlGoldenTests
{
    private static TableSchema Desired(DataProvider provider)
    {
        EntityAccessorRegistry.Get<DdlOwner>().ValueOrThrow();
        var map = EntityAccessorRegistry.Get<DdlItem>().ValueOrThrow().Map;
        return SchemaBuilder.FromMap(map, provider, new DataConnectionConfig()).ValueOrThrow();
    }

    private static IReadOnlyList<string> Create(DataProvider provider) => provider.Ddl.Generate(new CreateTableChange(Desired(provider)));

    [Fact]
    public void Create_table_per_provider()
    {
        Assert.Equal(
        [
            "CREATE TABLE `ddl_items` (`Id` bigint AUTO_INCREMENT NOT NULL, `Code` varchar(40) NOT NULL, `Note` varchar(255) NULL, " +
            "`Active` tinyint(1) NOT NULL, `OwnerId` bigint NOT NULL, PRIMARY KEY (`Id`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci",
            "CREATE UNIQUE INDEX `ux_ddl_items_Code` ON `ddl_items` (`Code`)",
            "ALTER TABLE `ddl_items` ADD CONSTRAINT `fk_ddl_items_OwnerId` FOREIGN KEY (`OwnerId`) REFERENCES `ddl_owner` (`Id`) ON DELETE CASCADE ON UPDATE RESTRICT",
        ], Create(MySqlDataProvider.Instance));

        Assert.Equal(
        [
            "CREATE TABLE \"public\".\"ddl_items\" (\"Id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, \"Code\" varchar(40) NOT NULL, " +
            "\"Note\" varchar(255) NULL, \"Active\" boolean NOT NULL, \"OwnerId\" bigint NOT NULL, PRIMARY KEY (\"Id\"))",
            "CREATE UNIQUE INDEX \"ux_ddl_items_Code\" ON \"public\".\"ddl_items\" (\"Code\")",
            "ALTER TABLE \"public\".\"ddl_items\" ADD CONSTRAINT \"fk_ddl_items_OwnerId\" FOREIGN KEY (\"OwnerId\") REFERENCES \"public\".\"ddl_owner\" (\"Id\") ON DELETE CASCADE ON UPDATE RESTRICT",
        ], Create(PostgreSqlDataProvider.Instance));

        var mssql = Create(SqlServerDataProvider.Instance);
        Assert.StartsWith("CREATE TABLE [dbo].[ddl_items] ([Id] bigint IDENTITY(1,1) NOT NULL, [Code] nvarchar(40) NOT NULL", mssql[0]);
        Assert.EndsWith("ON DELETE CASCADE ON UPDATE NO ACTION", mssql[2]);   // no RESTRICT on SQL Server

        Assert.Equal(
        [
            "CREATE TABLE \"ddl_items\" (\"Id\" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, \"Code\" text NOT NULL, \"Note\" text NULL, " +
            "\"Active\" integer NOT NULL, \"OwnerId\" integer NOT NULL, " +
            "CONSTRAINT \"fk_ddl_items_OwnerId\" FOREIGN KEY (\"OwnerId\") REFERENCES \"ddl_owner\" (\"Id\") ON DELETE CASCADE ON UPDATE RESTRICT)",
            "CREATE UNIQUE INDEX IF NOT EXISTS \"ux_ddl_items_Code\" ON \"ddl_items\" (\"Code\")",
        ], Create(SqliteDataProvider.Instance));
    }

    [Fact]
    public void Column_changes_per_provider()
    {
        var added = new AddColumnChange("t", null, new ColumnSchema("Qty", "int", false));
        Assert.Equal(["ALTER TABLE `t` ADD COLUMN `Qty` int NOT NULL DEFAULT 0"], MySqlDataProvider.Instance.Ddl.Generate(added));
        Assert.Equal(["ALTER TABLE [t] ADD [Qty] int NOT NULL DEFAULT 0"], SqlServerDataProvider.Instance.Ddl.Generate(added));
        Assert.Equal(["ALTER TABLE `t` ADD COLUMN `Body` longtext NOT NULL DEFAULT ('')"],
            MySqlDataProvider.Instance.Ddl.Generate(added with { Column = new ColumnSchema("Body", "longtext", false) }));

        var desired = new TableSchema("t", null, [new ColumnSchema("Name", "varchar(80)", true)], []);
        var altered = new AlterColumnChange("t", null, new ColumnSchema("Name", "varchar(40)", false), new ColumnSchema("Name", "varchar(80)", true), desired);
        Assert.Equal(["ALTER TABLE `t` MODIFY COLUMN `Name` varchar(80) NULL"], MySqlDataProvider.Instance.Ddl.Generate(altered));
        Assert.Equal(["ALTER TABLE \"t\" ALTER COLUMN \"Name\" TYPE varchar(80) USING \"Name\"::varchar(80)", "ALTER TABLE \"t\" ALTER COLUMN \"Name\" DROP NOT NULL"],
            PostgreSqlDataProvider.Instance.Ddl.Generate(altered));
        Assert.Equal(["ALTER TABLE [t] ALTER COLUMN [Name] varchar(80) NULL"], SqlServerDataProvider.Instance.Ddl.Generate(altered));

        var rebuild = SqliteDataProvider.Instance.Ddl.Generate(altered);
        Assert.Equal("CREATE TABLE \"t__cl_rebuild\" (\"Name\" varchar(80) NULL)", rebuild[0]);
        Assert.Equal("INSERT INTO \"t__cl_rebuild\" (\"Name\") SELECT \"Name\" FROM \"t\"", rebuild[1]);
        Assert.Equal(["DROP TABLE \"t\"", "ALTER TABLE \"t__cl_rebuild\" RENAME TO \"t\""], rebuild.Skip(2));

        var renamed = new RenameColumnChange("t", "dbo", "Old", "New");
        Assert.Equal(["EXEC sp_rename N'dbo.t.Old', N'New', N'COLUMN'"], SqlServerDataProvider.Instance.Ddl.Generate(renamed));
        Assert.Equal(["ALTER TABLE `t` RENAME COLUMN `Old` TO `New`"], MySqlDataProvider.Instance.Ddl.Generate(renamed with { Schema = null }));
    }

    [Fact]
    public void Index_and_foreign_key_changes_per_provider()
    {
        var index = new CreateIndexChange("t", null, new IndexSchema("ix_t_a", false, ["A"]) { Include = ["B"], Descending = [true] });
        Assert.Equal(["CREATE INDEX \"ix_t_a\" ON \"t\" (\"A\" DESC) INCLUDE (\"B\")"], PostgreSqlDataProvider.Instance.Ddl.Generate(index));
        Assert.Equal(["CREATE INDEX `ix_t_a` ON `t` (`A` DESC, `B`)"], MySqlDataProvider.Instance.Ddl.Generate(index));

        Assert.Equal(["DROP INDEX `ix` ON `t`"], MySqlDataProvider.Instance.Ddl.Generate(new DropIndexChange("t", null, "ix")));
        Assert.Equal(["DROP INDEX \"public\".\"ix\""], PostgreSqlDataProvider.Instance.Ddl.Generate(new DropIndexChange("t", "public", "ix")));

        var desired = new TableSchema("t", null, [new ColumnSchema("A", "int", false)], []);
        Assert.Equal(["ALTER TABLE `t` DROP FOREIGN KEY `fk`"], MySqlDataProvider.Instance.Ddl.Generate(new DropForeignKeyChange("t", null, "fk", desired)));
        Assert.Equal(["ALTER TABLE [t] DROP CONSTRAINT [fk]"], SqlServerDataProvider.Instance.Ddl.Generate(new DropForeignKeyChange("t", null, "fk", desired)));
        Assert.Equal(4, SqliteDataProvider.Instance.Ddl.Generate(new DropForeignKeyChange("t", null, "fk", desired)).Count);   // rebuild
    }
}
