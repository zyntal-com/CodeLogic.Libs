/// <summary>The outcome of a bulk copy.</summary>
/// <param name="Table">Target table.</param>
/// <param name="Rows">Rows copied.</param>
/// <param name="Duration">Time taken.</param>
/// <param name="Native">True when the provider's native bulk path ran; false for batched multi-row inserts.</param>
public sealed record BulkCopyReceipt(string Table, long Rows, TimeSpan Duration, bool Native);

/// <summary>Options for <see cref="DataBulk{T}.InsertAsync(IEnumerable{T}, BulkOptions?, CancellationToken)"/>.</summary>
public sealed record BulkOptions
{
    /// <summary>Rows buffered and sent per chunk (memory bound for streamed input).</summary>
    public int ChunkSize { get; init; } = 10_000;

    /// <summary>Copy the entities' identity values instead of letting the server generate them.</summary>
    public bool KeepIdentity { get; init; }
}

/// <summary>One chunk of rows for a provider's <see cref="BulkCopier"/>: values already in their stored form.</summary>
public sealed class BulkCopyRequest
{
    internal BulkCopyRequest(Database db, DbConnection connection, DbTransaction? transaction, TableRef table,
        IReadOnlyList<string> columns, IReadOnlyList<ColumnMap> maps, IReadOnlyList<SqlParameterValue?[]> rows, bool keepIdentity)
    {
        Database = db;
        Connection = connection;
        Transaction = transaction;
        Table = table;
        Columns = columns;
        Maps = maps;
        Rows = rows;
        KeepIdentity = keepIdentity;
    }

    /// <summary>The database (configuration, provider, type mapper).</summary>
    public Database Database { get; }

    /// <summary>Open connection to copy on.</summary>
    public DbConnection Connection { get; }

    /// <summary>The user transaction, when the copy runs inside one.</summary>
    public DbTransaction? Transaction { get; }

    /// <summary>Target table.</summary>
    public TableRef Table { get; }

    /// <summary>The target table, quoted for the dialect.</summary>
    public string QuotedTable => Database.Provider.Dialect.QuoteTable(Table.Name, Table.Schema);

    /// <summary>Column names, in row order.</summary>
    public IReadOnlyList<string> Columns { get; }

    /// <summary>Column metadata, in row order.</summary>
    public IReadOnlyList<ColumnMap> Maps { get; }

    /// <summary>Row values (null = SQL NULL), in column order.</summary>
    public IReadOnlyList<SqlParameterValue?[]> Rows { get; }

    /// <summary>True when identity values are copied (SQL Server needs <c>KeepIdentity</c>).</summary>
    public bool KeepIdentity { get; }

    /// <summary>Command timeout in seconds.</summary>
    public int TimeoutSeconds => Database.Config.CommandTimeoutSeconds;

    /// <summary>The driver parameter for a value: its stored value and database type, exactly as a normal insert binds it.</summary>
    public DbParameter Parameter(int row, int column) =>
        Rows[row][column] is { } value ? value.Create(Database.Provider.Types, "p") : NullParameter(column);

    /// <summary>The stored value as the driver sends it (<see cref="DBNull.Value"/> for NULL).</summary>
    public object StoreValue(int row, int column) => Parameter(row, column).Value ?? DBNull.Value;

    private DbParameter NullParameter(int column) => Database.Provider.Types.CreateParameter<object?>("p", null, Maps[column]);

    /// <summary>The rows as a forward-only reader of stored values (for SqlBulkCopy, MySqlBulkCopy).</summary>
    public DbDataReader CreateReader() => new BulkRowReader(this);
}

/// <summary>A provider's native bulk path. Returns null from <see cref="CopyAsync"/> when it is not available (CL.Data then batches inserts).</summary>
public abstract class BulkCopier
{
    /// <summary>Copies the chunk; returns the rows copied, or null when the native path cannot be used for this connection.</summary>
    public abstract Task<long?> CopyAsync(BulkCopyRequest request, CancellationToken ct);
}

/// <summary>
/// Bulk inserts for <typeparamref name="T"/> through the provider's native path (MySqlBulkCopy, SqlBulkCopy, PostgreSQL
/// <c>COPY BINARY</c>, prepared inserts in one transaction on SQLite), falling back to batched multi-row inserts.
/// <list type="bullet">
/// <item>Audit, tenant and concurrency columns are stamped, and values are converted exactly as a normal insert does.</item>
/// <item>Identity values generated by the server are not read back (use <c>InsertManyAsync</c> when you need them).</item>
/// <item>Entity save hooks and the command pipeline (interceptors, retries) do not run; the table's cached results are dropped.</item>
/// <item>Inside a transaction view the copy joins the transaction.</item>
/// </list>
/// </summary>
public sealed class DataBulk<T>
{
    private readonly Database _db;

    internal DataBulk(Database db) => _db = db;

    /// <summary>Copies <paramref name="entities"/> into their table.</summary>
    public async ValueTask<Result<BulkCopyReceipt>> InsertAsync(IEnumerable<T> entities, BulkOptions? options = null, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(entities);
        return await InsertAsync(ToAsync(entities), options, ct).ConfigureAwait(false);
    }

    /// <summary>Copies a stream of entities into their table, <see cref="BulkOptions.ChunkSize"/> rows at a time.</summary>
    public async ValueTask<Result<BulkCopyReceipt>> InsertAsync(IAsyncEnumerable<T> entities, BulkOptions? options = null, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(entities);
        options ??= new BulkOptions();
        var accessor = EntityAccessorRegistry.Get<T>();
        if (accessor.IsFailure) return accessor.Error!;
        var map = accessor.Value!.Map;
        if (!map.IsTable) return DataErrors.Unsupported($"'{map.ClrType.Name}' is a [DataRow] type and cannot be written.");

        var ctx = _db.WriteContext;
        var names = map.GetNames(ctx.Policy);
        var table = WritePlanner.TableOf(map, names, ctx);
        var maps = map.Columns.Where(c => c.DataType != DataType.RowVersion && (options.KeepIdentity || !c.Has(ColumnRoles.Identity))).ToArray();
        var columns = maps.Select(names.Of).ToArray();

        var started = Stopwatch.GetTimestamp();
        long total = 0;
        var native = false;
        try
        {
            List<SqlParameterValue?[]> chunk = new(Math.Min(options.ChunkSize, 1024));
            await foreach (var entity in entities.WithCancellation(ct).ConfigureAwait(false))
            {
                var row = WritePlanner.BulkRow(accessor.Value!, entity, maps, ctx);
                if (row.IsFailure) return row.Error!;
                chunk.Add(row.Value!);
                if (chunk.Count < options.ChunkSize) continue;
                var copied = await CopyChunkAsync(table, columns, maps, chunk, options, ct).ConfigureAwait(false);
                if (copied.IsFailure) return copied.Error!;
                (total, native) = (total + copied.Value.Rows, copied.Value.Native);
                chunk.Clear();
            }
            if (chunk.Count > 0)
            {
                var copied = await CopyChunkAsync(table, columns, maps, chunk, options, ct).ConfigureAwait(false);
                if (copied.IsFailure) return copied.Error!;
                (total, native) = (total + copied.Value.Rows, copied.Value.Native);
            }
        }
        finally
        {
            if (total > 0) _db.InvalidateCache([DataTags.Table(names.Table)]);
        }

        var receipt = new BulkCopyReceipt(names.Table, total, Stopwatch.GetElapsedTime(started), native);
        _db.Publish(new BulkCopyCompletedEvent(_db.Name, _db.Provider.Name, _db.Options.Time.GetUtcNow(), names.Table, total, receipt.Duration));
        return receipt;
    }

    private async ValueTask<Result<(long Rows, bool Native)>> CopyChunkAsync(TableRef table, string[] columns, ColumnMap[] maps,
        List<SqlParameterValue?[]> chunk, BulkOptions options, CancellationToken ct)
    {
        if (_db.Provider.BulkCopier is { } copier)
        {
            var native = await NativeAsync(copier, table, columns, maps, chunk, options, ct).ConfigureAwait(false);
            if (native.IsFailure) return native.Error!;
            if (native.Value is { } rows) return (rows, true);
        }
        var batched = await BatchedAsync(table, columns, chunk, ct).ConfigureAwait(false);
        return batched.IsFailure ? batched.Error! : (batched.Value, false);
    }

    private async ValueTask<Result<long?>> NativeAsync(BulkCopier copier, TableRef table, string[] columns, ColumnMap[] maps,
        List<SqlParameterValue?[]> chunk, BulkOptions options, CancellationToken ct)
    {
        DbConnection? owned = null;
        try
        {
            var (connection, transaction) = _db.Transaction is { } tx
                ? (tx.Handles.Connection, tx.Handles.Transaction)
                : (owned = await _db.Primary.DataSource.OpenConnectionAsync(ct).ConfigureAwait(false), (DbTransaction?)null);
            var request = new BulkCopyRequest(_db, connection, transaction, table, columns, maps, chunk, options.KeepIdentity);
            return await copier.CopyAsync(request, ct).ConfigureAwait(false);
        }
        catch (Exception ex)
        {
            return DataErrors.BulkFailed(table.Name, ex.Message, _db.Executor.Map(ex, ct));
        }
        finally
        {
            if (owned is not null) await owned.DisposeAsync().ConfigureAwait(false);
        }
    }

    /// <summary>The fallback: multi-row INSERTs sized to the provider's parameter limit, through the normal command path.</summary>
    private async ValueTask<Result<long>> BatchedAsync(TableRef table, string[] columns, List<SqlParameterValue?[]> chunk, CancellationToken ct)
    {
        var perStatement = Math.Max(1, Math.Min(_db.Config.MaxBatchSize, (_db.Provider.Capabilities.ParameterLimit - 1) / Math.Max(1, columns.Length)));
        long total = 0;
        for (var start = 0; start < chunk.Count; start += perStatement)
        {
            var count = Math.Min(perStatement, chunk.Count - start);
            var rows = new IReadOnlyList<SqlExpr>[count];
            for (var r = 0; r < count; r++)
            {
                var source = chunk[start + r];
                var row = new SqlExpr[source.Length];
                for (var c = 0; c < source.Length; c++) row[c] = source[c] is { } v ? new ParameterExpr(v) : NullExpr.Instance;
                rows[r] = row;
            }
            var rendered = _db.Render(new InsertStatement(table, columns, rows));
            if (rendered.IsFailure) return rendered.Error!;
            var context = new CommandContext(_db, new CommandSpec(rendered.Value!.Text, rendered.Value.Parameters), CommandKind.NonQuery, ct)
            {
                Operation = "insert",
                Table = table.Name,
                IsWrite = true,
            };
            var affected = await _db.RunAsync(context, 0, static async (cmd, _, token) => await cmd.ExecuteNonQueryAsync(token).ConfigureAwait(false),
                static n => n).ConfigureAwait(false);
            if (affected.IsFailure) return DataErrors.BulkFailed(table.Name, affected.Error!.Message, affected.Error);
            total += affected.Value;
        }
        return total;
    }

    private static async IAsyncEnumerable<T> ToAsync(IEnumerable<T> items)
    {
        foreach (var item in items) yield return item;
        await Task.CompletedTask.ConfigureAwait(false);
    }
}

/// <summary>A forward-only reader over a bulk chunk's stored values.</summary>
internal sealed class BulkRowReader(BulkCopyRequest request) : DbDataReader
{
    private int _row = -1;
    private object[]? _values;

    public override bool Read()
    {
        if (++_row >= request.Rows.Count)
        {
            _values = null;
            return false;
        }
        var values = new object[request.Columns.Count];
        for (var c = 0; c < values.Length; c++) values[c] = request.StoreValue(_row, c);
        _values = values;
        return true;
    }

    public override Task<bool> ReadAsync(CancellationToken cancellationToken) => Task.FromResult(Read());

    private object[] Current => _values ?? throw new InvalidOperationException("No current row.");

    public override int FieldCount => request.Columns.Count;
    public override object this[int ordinal] => GetValue(ordinal);
    public override object this[string name] => GetValue(GetOrdinal(name));
    public override int Depth => 0;
    public override bool HasRows => request.Rows.Count > 0;
    public override bool IsClosed => false;
    public override int RecordsAffected => -1;
    public override bool NextResult() => false;
    public override string GetName(int ordinal) => request.Columns[ordinal];

    public override int GetOrdinal(string name)
    {
        for (var i = 0; i < request.Columns.Count; i++)
            if (string.Equals(request.Columns[i], name, StringComparison.OrdinalIgnoreCase)) return i;
        throw new IndexOutOfRangeException(name);
    }

    public override object GetValue(int ordinal) => Current[ordinal];

    public override int GetValues(object[] values)
    {
        var count = Math.Min(values.Length, FieldCount);
        Array.Copy(Current, values, count);
        return count;
    }

    public override bool IsDBNull(int ordinal) => Current[ordinal] is DBNull;
    public override string GetDataTypeName(int ordinal) => GetFieldType(ordinal).Name;

    [return: DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicFields | DynamicallyAccessedMemberTypes.PublicProperties)]
    [UnconditionalSuppressMessage("Trimming", "IL2063", Justification = "Bulk copy only asks for the type to pick a converter; no members are reflected.")]
    [UnconditionalSuppressMessage("Trimming", "IL2073", Justification = "Bulk copy only asks for the type to pick a converter; no members are reflected.")]
    public override Type GetFieldType(int ordinal) =>
        _values is { } v && v[ordinal] is not DBNull ? v[ordinal].GetType() : Nullable.GetUnderlyingType(request.Maps[ordinal].ValueType) ?? request.Maps[ordinal].ValueType;

    public override bool GetBoolean(int ordinal) => (bool)GetValue(ordinal);
    public override byte GetByte(int ordinal) => (byte)GetValue(ordinal);
    public override char GetChar(int ordinal) => (char)GetValue(ordinal);
    public override DateTime GetDateTime(int ordinal) => (DateTime)GetValue(ordinal);
    public override decimal GetDecimal(int ordinal) => (decimal)GetValue(ordinal);
    public override double GetDouble(int ordinal) => (double)GetValue(ordinal);
    public override float GetFloat(int ordinal) => (float)GetValue(ordinal);
    public override Guid GetGuid(int ordinal) => (Guid)GetValue(ordinal);
    public override short GetInt16(int ordinal) => (short)GetValue(ordinal);
    public override int GetInt32(int ordinal) => (int)GetValue(ordinal);
    public override long GetInt64(int ordinal) => (long)GetValue(ordinal);
    public override string GetString(int ordinal) => (string)GetValue(ordinal);

    public override long GetBytes(int ordinal, long dataOffset, byte[]? buffer, int bufferOffset, int length)
    {
        var bytes = (byte[])GetValue(ordinal);
        if (buffer is null) return bytes.Length;
        var count = (int)Math.Max(0, Math.Min(length, bytes.Length - dataOffset));
        Array.Copy(bytes, dataOffset, buffer, bufferOffset, count);
        return count;
    }

    public override long GetChars(int ordinal, long dataOffset, char[]? buffer, int bufferOffset, int length)
    {
        var text = (string)GetValue(ordinal);
        if (buffer is null) return text.Length;
        var count = (int)Math.Max(0, Math.Min(length, text.Length - dataOffset));
        text.CopyTo((int)dataOffset, buffer, bufferOffset, count);
        return count;
    }

    public override System.Collections.IEnumerator GetEnumerator() => throw new NotSupportedException();
}
