using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CL.Data.Generator;

/// <summary>
/// Entry point of the CL.Data source generator. For every <c>[Table]</c> / <c>[DataRow]</c> type it emits an
/// <c>IEntityAccessor&lt;T&gt;</c>: the entity map (built from the same attribute instances reflection would read),
/// typed materialization and value access without reflection, and a module initializer that registers it.
/// Types it cannot map faithfully (generic, abstract, value types, inaccessible) are left to reflection mapping.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class DataGenerator : IIncrementalGenerator
{
    internal const string TableAttribute = "CL.Data.TableAttribute";
    internal const string DataRowAttribute = "CL.Data.DataRowAttribute";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var tables = context.SyntaxProvider.ForAttributeWithMetadataName(TableAttribute,
            static (node, _) => node is TypeDeclarationSyntax, static (ctx, ct) => EntityEmitter.Emit((INamedTypeSymbol)ctx.TargetSymbol, ct));
        var rows = context.SyntaxProvider.ForAttributeWithMetadataName(DataRowAttribute,
            static (node, _) => node is TypeDeclarationSyntax, static (ctx, ct) => EntityEmitter.Emit((INamedTypeSymbol)ctx.TargetSymbol, ct));

        var entities = tables.Collect().Combine(rows.Collect())
            .Select(static (pair, _) => pair.Left.AddRange(pair.Right)
                .Where(e => e.Source is not null)
                .GroupBy(e => e.HintName).Select(g => g.First())   // a type with both attributes is emitted once
                .OrderBy(e => e.HintName, System.StringComparer.Ordinal)
                .ToImmutableArray());

        context.RegisterSourceOutput(entities, static (spc, list) =>
        {
            if (list.IsDefaultOrEmpty) return;
            var registrations = new StringBuilder();
            foreach (var entity in list)
            {
                spc.AddSource(entity.HintName + ".g.cs", entity.Source!);
                registrations.Append("        ").Append(entity.Registration).Append('\n');
            }
            spc.AddSource("CLDataAccessorRegistration.g.cs",
                "// <auto-generated/>\n#nullable enable\nnamespace CL.Data.Generated;\n\n" +
                "[global::System.CodeDom.Compiler.GeneratedCode(\"CL.Data.Generator\", \"1.0\")]\n" +
                "internal static class CLDataAccessorRegistration\n{\n" +
                "    [global::System.Runtime.CompilerServices.ModuleInitializer]\n" +
                "    internal static void Register()\n    {\n" + registrations + "    }\n}\n");
        });
    }
}

/// <summary>The generated source for one entity (all strings, so the incremental pipeline can compare results).</summary>
internal readonly struct EmittedEntity : System.IEquatable<EmittedEntity>
{
    public EmittedEntity(string hintName, string? source, string? registration)
    {
        HintName = hintName;
        Source = source;
        Registration = registration;
    }

    public string HintName { get; }
    public string? Source { get; }
    public string? Registration { get; }

    public bool Equals(EmittedEntity other) => HintName == other.HintName && Source == other.Source && Registration == other.Registration;
    public override bool Equals(object? obj) => obj is EmittedEntity other && Equals(other);
    public override int GetHashCode() => (HintName?.GetHashCode() ?? 0) ^ (Source?.GetHashCode() ?? 0);
}

internal static class EntityEmitter
{
    private static readonly SymbolDisplayFormat Fqn = EntityShape.Fqn;

    public static EmittedEntity Emit(INamedTypeSymbol type, CancellationToken ct)
    {
        var hint = HintName(type);
        var shape = EntityShape.Analyze(type);
        if (!shape.CanGenerate) return new EmittedEntity(hint, null, null);   // the analyzer reports why
        var mapped = shape.Mapped;
        var setsRequired = shape.SetsRequiredMembers;

        ct.ThrowIfCancellationRequested();
        var typeName = type.ToDisplayString(Fqn);
        var accessor = hint;
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0618 // obsolete members are still mapped\n");
        sb.Append("namespace CL.Data.Generated;\n\n");
        sb.Append("/// <summary>Generated CL.Data mapping for <see cref=\"").Append(typeName.Replace("global::", "").Replace('<', '{').Replace('>', '}')).Append("\"/>.</summary>\n");
        sb.Append("[global::System.CodeDom.Compiler.GeneratedCode(\"CL.Data.Generator\", \"1.0\")]\n");
        sb.Append("internal sealed class ").Append(accessor).Append(" : global::CL.Data.Mapping.IEntityAccessor<").Append(typeName).Append(">\n{\n");

        // Map (built on first use).
        sb.Append("    private global::CL.Data.Mapping.EntityMap? _map;\n\n");
        sb.Append("    public global::CL.Data.Mapping.EntityMap Map => _map ?? global::System.Threading.Interlocked.CompareExchange(ref _map, BuildMap(), null) ?? _map!;\n\n");
        sb.Append("    private static global::CL.Data.Mapping.EntityMap BuildMap() => global::CL.Data.Mapping.GeneratedMapping.Entity(\n");
        sb.Append("        typeof(").Append(typeName).Append("),\n        new global::System.Attribute[] { ");
        sb.Append(string.Join(", ", DataAttributes(type.GetAttributes())));
        sb.Append(" },\n        new global::CL.Data.Mapping.ColumnMap[]\n        {\n");
        foreach (var p in mapped)
        {
            sb.Append("            global::CL.Data.Mapping.GeneratedMapping.Column(\"").Append(p.Name).Append("\", typeof(").Append(p.TypeName).Append("), ")
              .Append(p.Nullable ? "true" : "false").Append(", new global::System.Attribute[] { ").Append(string.Join(", ", DataAttributes(p.Attributes.ToImmutableArray()))).Append(" }, ")
              .Append(p.Converter is null ? "null" : "new " + p.Converter.ToDisplayString(Fqn) + "()").Append("),\n");
        }
        sb.Append("        });\n\n");

        // Materialize.
        sb.Append("    public ").Append(typeName).Append(" Materialize(global::System.Data.Common.DbDataReader reader, global::System.ReadOnlySpan<int> ordinals)\n    {\n");
        sb.Append("        var columns = Map.Columns;\n");
        var args = mapped.Where(p => p.CtorParameter >= 0).OrderBy(p => p.CtorParameter)
            .Select(p => Read(p, mapped.IndexOf(p), p.CtorParameterType!));
        var initializers = setsRequired ? [] : mapped.Where(p => p.Required && p.CtorParameter < 0).ToList();
        sb.Append("        var entity = new ").Append(typeName).Append('(').Append(string.Join(", ", args)).Append(')');
        if (initializers.Count > 0)
            sb.Append(" { ").Append(string.Join(", ", initializers.Select(p => p.Name + " = " + Read(p, mapped.IndexOf(p), p.TypeName)))).Append(" }");
        sb.Append(";\n");
        for (var i = 0; i < mapped.Count; i++)
        {
            var p = mapped[i];
            if (p.CtorParameter >= 0 || initializers.Contains(p) || p.Setter == SetterKind.None) continue;
            var value = "global::CL.Data.Mapping.GeneratedMapping.Read<" + p.TypeName + ">(reader, ordinals[" + i + "], columns[" + i + "])";
            sb.Append("        if (ordinals[").Append(i).Append("] >= 0) ")
              .Append(p.Setter == SetterKind.Init ? "Set_" + p.Name + "(entity, " + value + ")" : "entity." + p.Name + " = " + value).Append(";\n");
        }
        sb.Append("        return entity;\n    }\n\n");

        // WriteColumn.
        sb.Append("    public void WriteColumn(").Append(typeName).Append(" entity, int column, global::CL.Data.Mapping.IColumnValueWriter writer)\n    {\n");
        sb.Append("        var columns = Map.Columns;\n        switch (column)\n        {\n");
        for (var i = 0; i < mapped.Count; i++)
            sb.Append("            case ").Append(i).Append(": writer.Write(columns[").Append(i).Append("], entity.").Append(mapped[i].Name).Append("); return;\n");
        sb.Append("            default: throw new global::System.ArgumentOutOfRangeException(nameof(column));\n        }\n    }\n\n");

        // GetValue.
        sb.Append("    public object? GetValue(").Append(typeName).Append(" entity, int column) => column switch\n    {\n");
        for (var i = 0; i < mapped.Count; i++) sb.Append("        ").Append(i).Append(" => entity.").Append(mapped[i].Name).Append(",\n");
        sb.Append("        _ => throw new global::System.ArgumentOutOfRangeException(nameof(column)),\n    };\n\n");

        // SetValue.
        sb.Append("    public void SetValue<TValue>(").Append(typeName).Append(" entity, int column, TValue value)\n    {\n");
        sb.Append("        var columns = Map.Columns;\n        switch (column)\n        {\n");
        for (var i = 0; i < mapped.Count; i++)
        {
            var p = mapped[i];
            var converted = "global::CL.Data.Mapping.GeneratedMapping.Convert<TValue, " + p.TypeName + ">(value, columns[" + i + "])";
            sb.Append("            case ").Append(i).Append(": ");
            sb.Append(p.Setter switch
            {
                SetterKind.Set => "entity." + p.Name + " = " + converted + "; return;",
                SetterKind.Init => "Set_" + p.Name + "(entity, " + converted + "); return;",
                _ => "throw global::CL.Data.Mapping.GeneratedMapping.NotSettable(typeof(" + typeName + "), columns[" + i + "]);",
            }).Append('\n');
        }
        sb.Append("            default: throw new global::System.ArgumentOutOfRangeException(nameof(column));\n        }\n    }\n\n");

        // GetKey.
        sb.Append("    public global::CL.Data.Mapping.EntityKey GetKey(").Append(typeName).Append(" entity)\n    {\n");
        sb.Append("        var key = Map.Key.Columns;\n        switch (key.Count)\n        {\n");
        sb.Append("            case 0: return default;\n");
        sb.Append("            case 1: return global::CL.Data.Mapping.EntityKey.Of((object?)GetValue(entity, key[0].Ordinal));\n");
        sb.Append("            default:\n                var values = new object?[key.Count];\n");
        sb.Append("                for (var i = 0; i < values.Length; i++) values[i] = GetValue(entity, key[i].Ordinal);\n");
        sb.Append("                return global::CL.Data.Mapping.EntityKey.Of((global::System.ReadOnlySpan<object?>)values);\n        }\n    }\n");

        // Init-only setters through UnsafeAccessor (no reflection, AOT-safe).
        foreach (var p in mapped.Where(p => p.Setter == SetterKind.Init))
        {
            sb.Append("\n    [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = \"set_")
              .Append(p.Name).Append("\")]\n");
            sb.Append("    private static extern void Set_").Append(p.Name).Append('(').Append(typeName).Append(" entity, ").Append(p.TypeName).Append(" value);\n");
        }
        sb.Append("}\n");

        var registration = "global::CL.Data.Mapping.EntityAccessorRegistry.Register<" + typeName + ">(new " + accessor + "());";
        return new EmittedEntity(hint, sb.ToString(), registration);
    }

    private static string Read(ShapeProperty p, int index, string type) =>
        "ordinals[" + index + "] >= 0 ? global::CL.Data.Mapping.GeneratedMapping.Read<" + type + ">(reader, ordinals[" + index + "], columns[" + index + "]) : default!";

    /// <summary>C# expressions creating the CL.Data attributes in <paramref name="attributes"/>, exactly as declared.</summary>
    internal static IEnumerable<string> DataAttributes(ImmutableArray<AttributeData> attributes)
    {
        foreach (var attribute in attributes)
        {
            var cls = attribute.AttributeClass;
            if (cls is null || cls.ContainingNamespace?.ToDisplayString() != "CL.Data") continue;
            var sb = new StringBuilder("new ").Append(cls.ToDisplayString(Fqn)).Append('(');
            sb.Append(string.Join(", ", attribute.ConstructorArguments.Select(Literal)));
            sb.Append(')');
            if (attribute.NamedArguments.Length > 0)
                sb.Append(" { ").Append(string.Join(", ", attribute.NamedArguments.Select(n => n.Key + " = " + Literal(n.Value)))).Append(" }");
            yield return sb.ToString();
        }
    }

    internal static string Literal(TypedConstant constant)
    {
        if (constant.IsNull) return constant.Type is null ? "null" : "(" + constant.Type.ToDisplayString(Fqn) + ")null";
        switch (constant.Kind)
        {
            case TypedConstantKind.Array:
                return "new " + ((IArrayTypeSymbol)constant.Type!).ElementType.ToDisplayString(Fqn) + "[] { " + string.Join(", ", constant.Values.Select(Literal)) + " }";
            case TypedConstantKind.Type:
                return "typeof(" + ((ITypeSymbol)constant.Value!).ToDisplayString(Fqn) + ")";
            case TypedConstantKind.Enum:
                return "(" + constant.Type!.ToDisplayString(Fqn) + ")(" + SymbolDisplay.FormatPrimitive(constant.Value!, quoteStrings: false, useHexadecimalNumbers: false) + ")";
            default:
                return constant.Value switch
                {
                    string s => SymbolDisplay.FormatLiteral(s, quote: true),
                    char c => SymbolDisplay.FormatLiteral(c, quote: true),
                    bool b => b ? "true" : "false",
                    _ => "(" + constant.Type!.ToDisplayString(Fqn) + ")(" + SymbolDisplay.FormatPrimitive(constant.Value!, quoteStrings: false, useHexadecimalNumbers: false) + ")",
                };
        }
    }

    /// <summary>A unique, valid class name for the accessor of <paramref name="type"/>.</summary>
    private static string HintName(INamedTypeSymbol type)
    {
        var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", "");
        var sb = new StringBuilder();
        foreach (var ch in name) sb.Append(char.IsLetterOrDigit(ch) ? ch : '_');
        return sb.Append("_DataAccessor").ToString();
    }
}
